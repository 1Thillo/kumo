root = pathlib.Path(__file__).resolve().parent.parent
used = []
for f in sorted((root / "ui").glob("*.slint")):
    for m in re.finditer(r'@tr\("((?:[^"\\]|\\.)*)"', f.read_text(encoding="utf-8")):
        if m.group(1) not in used:
            used.append(m.group(1))
missing = [s for s in used if s not in DE]
if missing:
    raise SystemExit("missing translations:\n" + "\n".join(missing))


def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


out = ['msgid ""', 'msgstr ""', '"Content-Type: text/plain; charset=UTF-8\\n"', '"Language: de\\n"', ""]
for s in used:
    out += [f'msgid "{esc(s)}"', f'msgstr "{esc(DE[s])}"', ""]
path = root / "lang" / "de" / "LC_MESSAGES" / "kumo.po"
path.write_text("\n".join(out), encoding="utf-8")
print(f"{len(used)} strings written to {path}")
